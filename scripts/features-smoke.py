#!/usr/bin/env python3
"""Isolated 0.2 feature smoke; never reads the production config or token."""
import argparse
import json
import os
import pathlib
import signal
import subprocess
import threading
import time
import urllib.error
import urllib.request
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

parser = argparse.ArgumentParser()
parser.add_argument('--binary', required=True)
parser.add_argument('--work-dir', required=True)
parser.add_argument('--hold', type=int, default=0)
args = parser.parse_args()
work = pathlib.Path(args.work_dir).resolve()
work.mkdir(parents=True, exist_ok=False)
os.chmod(work, 0o700)

class Mock(BaseHTTPRequestHandler):
    def do_GET(self):
        code = 401 if self.path.startswith('/auth') else 404 if self.path.startswith('/missing') else 200
        self.send_response(code)
        self.end_headers()
        self.wfile.write(b'isolated')
    def log_message(self, *args):
        pass

mock = ThreadingHTTPServer(('127.0.0.1', 0), Mock)
threading.Thread(target=mock.serve_forever, daemon=True).start()
url = 'http://127.0.0.1:' + str(mock.server_address[1])
# Only synthetic loopback endpoints. The token is generated by the isolated kernel.
config = work / 'config.yaml'
config.write_text(f'''version: 1
data_dir: {work / 'data'}
admin:
  listen: 127.0.0.1:18766
health:
  enabled: true
  interval: 2s
  fail_threshold: 1
  timeout: 1s
retry:
  backoff: 0s
groups:
  - name: smoke-auth
    listen: 127.0.0.1:18765
    comment: 隔离演示 · 认证端点
    upstreams:
      - name: auth
        url: {url}
        probe:
          path: /auth
      - name: notfound
        url: {url}
        probe:
          path: /missing
      - name: healthy
        url: {url}
        probe:
          path: /ready
  - name: smoke-other
    listen: 127.0.0.1:18767
    upstreams:
      - name: direct
        url: {url}
''', encoding='utf-8')
os.chmod(config, 0o600)
log = (work / 'kernel.log').open('wb')
proc = subprocess.Popen([args.binary, '-config', str(config)], stdout=log, stderr=subprocess.STDOUT)
(work / 'pid').write_text(str(proc.pid))

def request(path, method='GET', payload=None, port=18766, ua=None):
    headers = {'X-Linkgate-Token': token}
    if ua:
        headers['User-Agent'] = ua
    data = None
    if payload is not None:
        data = json.dumps(payload).encode()
        headers['Content-Type'] = 'application/json'
    req = urllib.request.Request('http://127.0.0.1:' + str(port) + path, data=data, method=method, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=5) as r:
            b = r.read()
            return json.loads(b) if r.headers.get_content_type() == 'application/json' else b
    except urllib.error.HTTPError as e:
        if port == 18765:
            return e.read()
        raise

try:
    for _ in range(100):
        if proc.poll() is not None:
            raise RuntimeError('isolated kernel exited before ready')
        token_file = work / 'data' / 'admin.token'
        if token_file.exists():
            token = token_file.read_text().strip()
            try:
                status = request('/__linkgate/v1/status')
                break
            except OSError:
                pass
        time.sleep(.1)
    else:
        raise RuntimeError('startup timeout')
    assert status['version'] == '0.2.1'
    results = {}
    for line, code, cls in [('auth', 401, 'auth'), ('notfound', 404, 'notfound'), ('healthy', 200, 'healthy')]:
        result = request('/__linkgate/v1/probe?group=smoke-auth&upstream=' + line, 'POST')
        assert result['reach'] is True and result['class'] == cls and result['http_status'] == code, result
        results[line] = result
    status = request('/__linkgate/v1/status')
    assert status['groups'][0]['upstreams'][0]['reach'] is True
    for i in range(24):
        request('/ok', port=18765, ua=['claude-code/1','codex/1','opencode/1','zcode/1','curl/8'][i % 5])
    request('/__linkgate/v1/toggle?group=smoke-auth&upstream=healthy&enabled=false', 'POST')
    for i in range(8):
        request('/auth', port=18765, ua=['claude-code/1','curl/8'][i % 2])
    events = request('/__linkgate/v1/events?group=smoke-auth&stream=state')
    assert events['events'] and all(e.get('group') == 'smoke-auth' for e in events['events'])
    assert any(e.get('group') != 'smoke-auth' for e in request('/__linkgate/v1/events')['events'])
    request('/__linkgate/v1/ui/order', 'PUT', {'sort_mode':'manual','service_order':['smoke-other','smoke-auth']})
    assert request('/__linkgate/v1/status')['groups'][0]['name'] == 'smoke-other'
    assert 'service_order:' in config.read_text() and config.with_suffix('.yaml.bak').exists()
    request('/__linkgate/v1/groups/smoke-auth/upstreams/order', 'PUT', {'order':['auth','notfound','healthy']})
    settings = request('/__linkgate/v1/settings')
    assert settings['settings']['log']['level'] == 'info'
    request('/__linkgate/v1/settings', 'PUT', {'log':{'ring_size':250,'level':'debug','format':'json'}})
    settings = request('/__linkgate/v1/settings')
    assert settings['active_settings']['log']['format'] == 'text'
    assert 'log.format' in settings['pending_restart']
    stats = request('/__linkgate/v1/stats')
    auth = next(g for g in stats['groups'] if g['name'] == 'smoke-auth')
    assert auth['total'] == 32 and auth['ua_lines'], auth
    output = {'probe':results,'service_total':auth['total'],'ua_lines':auth['ua_lines'],'events_filtered':len(events['events']),'pending_restart':settings['pending_restart'],'version':status['version']}
    (work / 'results.json').write_text(json.dumps(output, ensure_ascii=False, indent=2))
    os.chmod(work / 'results.json', 0o600)
    print('PASS isolated feature smoke: auth/404 classes, status, events, settings/pending, stats/UA, persisted service/batch order', flush=True)
    if args.hold:
        print('Holding isolated instance for UI verification', flush=True)
        time.sleep(args.hold)
finally:
    proc.send_signal(signal.SIGTERM)
    try:
        proc.wait(timeout=8)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait()
    mock.shutdown()
    log.close()
